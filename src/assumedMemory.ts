// "Assumed Memory" — when a day has photos but the app can only guess what
// actually happened, this reconstructs a plausible, clearly-speculative
// account from the photos alone: what's in them, and when each was taken.
// Read-only and dismissible — it never becomes the user's real logged Day
// memory (see memoryLog.ts), it's just the AI's best guess floating
// alongside it on the Timeline.

export function assumedMemoryAvailable(): boolean {
  return visionAvailable();
}

// The day's own words, as one string — what the analysis is given as
// ground truth to complement, and part of the cache signature.
//
// This MUST be derived identically everywhere (Timeline, Day detail, the
// background pass). It previously wasn't: each caller built it slightly
// differently, so they each computed a different signature for the same
// day and kept regenerating each other's work in a loop. Always sorted by
// time so the string is stable regardless of what order the caller's list
// happened to be in.
export function dayLoggedText(memories: LoggedMemory[]): string {
  return [...memories]
    .sort((a, b) => a.takenAt.localeCompare(b.takenAt))
    .map((m) => m.text?.trim())
    .filter(Boolean)
    .join(' ');
}

// Bump whenever the analysis prompt changes in a way that should rewrite
// existing summaries. Cached records generated under an older version are
// treated as stale and regenerated by the normal background pass — no
// manual cache wipe, and no re-analysing everything for prompt tweaks that
// don't warrant it.
//   1 — original ("warm narrative", heavy hedging)
//   2 — direct, concrete tone; no mood/filler words
//   3 — screenshots/saved images no longer treated as events of that day
export const PROMPT_VERSION = 3;

export type AssumedMemory = {
  summary: string;
  // Translated copies of `summary`, keyed by language code — filled in on
  // demand the first time the user taps "Translate" for that language, then
  // cached alongside the original so it's never re-translated.
  translations?: Record<string, string>;
  generatedAt: string;
  signature: string;
  // Which prompt wrote this summary. Absent on records from before
  // versioning existed, which correctly reads as stale.
  promptVersion?: number;
};

// A cached record is only reusable if it was built from the same photos AND
// by the current prompt.
function isFresh(cached: AssumedMemory | null | undefined, signature: string): boolean {
  // Deliberately does NOT require the current PROMPT_VERSION.
  //
  // It used to, which meant every prompt tweak silently invalidated every
  // day at once — hundreds of queued vision calls on every single app
  // launch, saturating the account's tokens-per-minute budget for 20+
  // minutes and starving the Ask chat of the quota it needs to answer
  // anything. A wording improvement is never worth breaking the main
  // feature of the app.
  //
  // So: an existing analysis is kept regardless of which prompt wrote it.
  // Only genuinely new or changed days (different photos / edited logged
  // text) cost an API call. PROMPT_VERSION is still recorded on new
  // records, so a deliberate, user-triggered rewrite can find the old ones
  // later — see regenerateStaleAnalyses().
  return !!cached && cached.signature === signature;
}

// Days whose analysis predates the current prompt. Nothing calls this
// automatically — it exists so a rewrite can be offered as an explicit,
// opt-in action rather than something that quietly eats the budget.
export async function countOutdatedAnalyses(): Promise<number> {
  const all = await getAllAssumedMemories();
  return Object.values(all).filter((r) => r.promptVersion !== PROMPT_VERSION).length;
}

// Drops the cached analyses written by older prompts so the normal
// background pass regenerates them in the current tone. Opt-in only.
export async function regenerateStaleAnalyses(): Promise<number> {
  const all = await getAllAssumedMemories();
  const stale = Object.entries(all).filter(([, r]) => r.promptVersion !== PROMPT_VERSION);
  await AsyncStorage.multiRemove(stale.map(([day]) => CACHE_PREFIX + day));
  return stale.length;
}

